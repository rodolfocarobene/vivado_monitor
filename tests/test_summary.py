def full_record(**kw):
    r, _ = full("100", 1_700_000_000.0, project="/p/top.runs", part="xc7", board="b1", vivado_version="2024.2",
                strategy_synth="S", strategy_impl="I", host="node1", directives={"place_design": "Explore"},
                counts=[1, 2, 3, 4], failure=None,
                utilization={"LUT": {"used": 1234, "available": 5000, "pct": 24.7}},
                artifacts=[{"kind": "bitstream", "label": "Bitstream", "step": None, "path": "/p/top.bit", "current": False},
                           {"kind": "utilization", "label": "Utilization", "step": "place_design", "path": "/p/u.rpt"}],
                attempts=[{"n": 1, "mode": "project", "result": "failed", "detail": "Route Design: failed: crash"},
                          {"n": 2, "mode": "resume", "result": "done", "detail": None}])
    return {**r, **kw}


def test_markdown_full_record_sections_in_order():
    md = summary.to_markdown(full_record(), generated_at=1_700_000_000)
    heads = [line for line in md.splitlines() if line.startswith("#")]
    assert heads == ["# top build summary", "## Build info", "## Timing", "## Utilization", "## Step durations",
                     "## Messages", "## Attempts", "## Reports and bitstream"]
    assert "**Finished, timing met**" in md and "Duration 1m 40s" in md
    assert "- **Project:** `/p/top.runs`" in md and "- **Directive: place_design:** `Explore`" in md
    assert "| Clock | WNS (ns) | WHS (ns) |" in md and "| `clk` | 0.100 | 0.050 |" in md
    assert "| LUT | 1,234 | 5,000 | 24.7% |" in md
    assert "| `synth_design` | 1m 00s | 60.0% |" in md
    assert md.index("`CW1`") < md.index("`W1`") < md.index("`W2`")                  # worse first, then by count
    assert "| 2 | Resume from checkpoint | Done |" in md
    assert "replaced by a later build" in md
    assert md.rstrip().endswith("_Generated by vmon %s on 2023-11-14_" % summary.__version__)


def test_minimal_old_record_omits_sections():
    md = summary.to_markdown(rec("1", started=1_700_000_000.0))
    assert [l for l in md.splitlines() if l.startswith("#")] == ["# top build summary"]
    assert "Finished, timing met" in md and "Generated by vmon" in md
