def test_not_final_timing_and_clock_cap():
    clocks = {"c%02d" % i: {"wns": float(i), "whs": 0.0} for i in range(30)}
    md = summary.to_markdown(full_record(timing={"wns": -1.0, "tns": -2.0, "whs": 0.1, "ths": 0.0, "final": False},
                                         timing_clocks=clocks))
    assert "Not final" in md and "_Worst 10 of 30 clocks by WNS._" in md
    assert "`c00`" in md and "`c09`" in md and "`c10`" not in md


def test_message_cap_keeps_all_serious():
    msgs = {"W%d" % i: {"severity": "warning", "count": i + 1, "text": "w"} for i in range(40)}
    msgs |= {"E%d" % i: {"severity": "error", "count": 1, "text": "e"} for i in range(3)}
    shown, hidden = summary.top_messages(msgs)
    assert len(shown) == 15 and hidden == 28 and [i for i, _ in shown[:3]] == ["E0", "E1", "E2"]
    assert shown[3][0] == "W39"
    many = {"E%d" % i: {"severity": "error", "count": 1, "text": "e"} for i in range(20)}
    assert len(summary.top_messages(many)[0]) == 20


def test_outcome_wording():
    for result, text in (("met", "Finished, timing met"), ("timing_not_met", "Finished, timing not met"),
                         ("stopped", "Stopped"), ("done", "Finished")):
        assert summary.outcome({"result": result}) == text
    assert summary.outcome({"result": "failed", "failure": {"step": "Route Design", "reason": "crash"}}) == "Failed: Route Design: crash"
    assert summary.outcome({"result": "failed", "failure": {"step": None, "reason": "Build failed"}}) == "Failed: Build failed"
    assert summary.outcome({"result": "failed"}) == "Failed"


def test_escaping_markdown_and_html():
    evil = {"X|1": {"severity": "warning", "count": 1, "text": "a | b <script>alert(1)</script> *x* `c`"}}
    r = full_record(messages=evil, firmware="<b>fw</b>")
    md = summary.to_markdown(r)
    row = next(l for l in md.splitlines() if "X\\|1" in l)
    assert row.count("|") - row.count("\\|") == 5                                  # 4 cells: pipes in text are escaped
    assert "a \\| b \\<script\\>" in row and "\\*x\\*" in row and "\\`c\\`" in row
    page = summary.to_html(r)
    assert "<script>" not in page and "<b>fw</b>" not in page
    assert "&lt;script&gt;alert(1)&lt;/script&gt;" in page and "&lt;b&gt;fw&lt;/b&gt; build summary" in page
    assert "http" not in page.replace("http-equiv", "")                              # no external assets


def test_html_is_self_contained_document():
    page = summary.to_html(full_record())
    assert page.startswith("<!doctype html>") and "<style>" in page and "@media print" in page
    assert "<link" not in page and "src=" not in page
    assert page.count("<table>") == 8 and "Finished, timing met" in page


def test_filename_sanitised():
    r = {"firmware": "my fw/../x", "started_at": 1_700_000_000.0, "build": "1"}
    name = summary.filename(r, "md")
    assert name.endswith("_summary.md") and "/" not in name and " " not in name and not name.startswith(".")
    assert summary.filename({"firmware": "top", "build": "77"}, "html") == "top_77_summary.html"


def test_attempts_of_record(tmp_path, cfg):
    monitor, fw_id = finished_monitor(tmp_path, cfg)
    assert monitor.history.load(fw_id)[0]["attempts"] is None              # single attempt: no section
    fw = monitor.firmwares[fw_id]
    node = fw.flows[-1].stages[-1]
    node.attempts = [{"n": 1, "mode": "project", "status": "failed", "summary": "failed: boom"},
                     {"n": 2, "mode": "resume", "status": "done", "summary": "done"}]
    out = history.attempts_of(fw)
    assert [(a["n"], a["mode"], a["result"]) for a in out] == [(1, "project", "failed"), (2, "resume", "done")]
    assert out[0]["detail"].endswith(": failed: boom") and out[1]["detail"] is None
    monitor.stop()


def test_summary_api(tmp_path, cfg):
    monitor, fw_id = finished_monitor(tmp_path, cfg)
    server = make_server(monitor, "127.0.0.1", 0)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    base = "http://127.0.0.1:%d/api/history/summary?fw=%s" % (server.server_address[1], fw_id)
    try:
        build = json.load(get("http://127.0.0.1:%d/api/history?fw=%s" % (server.server_address[1], fw_id)))["builds"][0]["build"]
        md = get("%s&build=%s" % (base, build))
        assert md.code == 200 and md.headers["Content-Type"] == "text/markdown; charset=utf-8"
        assert "Content-Disposition" not in md.headers and md.read().decode().startswith("# top build summary")
        page = get("%s&build=%s&format=html" % (base, build))
        assert page.headers["Content-Type"] == "text/html; charset=utf-8" and b"<!doctype html>" in page.read()
        dl = get("%s&build=%s&format=md&download=1" % (base, build))
        disp = dl.headers["Content-Disposition"]
        assert disp.startswith('attachment; filename="top_') and disp.endswith('_summary.md"')
        assert get("%s&build=%s&format=html&download=1" % (base, build)).headers["Content-Disposition"].endswith('_summary.html"')
        assert get("%s&build=%s&format=pdf" % (base, build)).code == 400
        for bad in ("&build=nope", ""):
            assert get(base + bad).code == 404
        assert get("http://127.0.0.1:%d/api/history/summary?fw=../x&build=%s" % (server.server_address[1], build)).code == 404
        assert get("http://127.0.0.1:%d/api/history/summary?fw=zzz&build=1" % server.server_address[1]).code == 404
    finally:
        server.shutdown()
        monitor.stop()


def test_exported_summaries_leave_out_the_host():
    """Summaries are meant to be shared: the build host (IP or machine name) is recorded but never exported."""
    r = full_record(host="10.1.2.3")
    assert "10.1.2.3" not in summary.to_markdown(r) and "Host" not in summary.to_markdown(r)
    assert "10.1.2.3" not in summary.to_html(r)
